# Histogram:
# A visual representation of the distribution of quantitative data.
# They group values into bins(intervals)
# and counts how many falls in each range.


# Difference btn BarChart and Histogram
# | Feature   | **Bar Chart**       | **Histogram**       |
# | --------- | ------------------- | ------------------- |
# | Data type | Categorical         | Continuous          |
# | X-axis    | Categories (names)  | Value ranges (bins) |
# | Bars      | **Separated**       | **Touching**        |
# | Shows     | Comparison          | Distribution        |
# | Order     | Any order           | Fixed order         |
# | Example   | Students by faculty | Marks distribution  |


