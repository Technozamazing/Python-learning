# What is the difference between for loop in Python and in C?

# In C, for loop is primarily used with a counter variable to iterate a specific number of times.
# In Python, for loop is used to iterate over elements of a sequence (like list, tuple, string, etc.) 
# directly without needing a counter variable.

# The primary difference is that a C for loop is a condition-controlled loop using an index variable, whereas a Python for loop is an iterator-based loop (a "for-each" loop) that iterates directly over items in a sequence. 

# Key Differences
# Feature 	                                     C for Loop	                                                                  Python for Loop
# Type of Iteration	          - Condition-controlled (definite iteration)	                               - Iterator-based (iterates over a sequence)
# Syntax	                  - for (initialization; condition; increment)	                               - for iterating_var in sequence:
# Control Variable            -	An index variable that can be explicitly modified within                   - A variable that gets a new value assigned to it from the iterable at the start of each iteration;
#                               the loop body to affect the next iteration.	                                 changes within the loop body are lost in the next cycle.
# Explicit Control	          - Requires explicit initialization, condition checking, and                  - Manages iteration automatically using the iterator protocol, abstracting away index management.
#                               increment/decrement logic.	
# Data Types	              - Typically used with basic data types and arrays using explicit indexing.   - Works with any iterable object, such as lists, tuples, strings, or dictionaries.


