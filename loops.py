# range() function in Python:
# Range functions returns a sequence of numbers, starting from 0 by default, and increments by 
# 1 (by default), and stops before a specified number.

# Syntax: range(start?, stop, step?)
# By default: range(0, stop, 1 )


# Example of range() function:
for i in range(5):  #range(0, 5, 1)  - 0 to 4, 5 is excluded
    print(i)

for i in range(1, 5):  #range(1, 5, 1) - 1 to 4, 5 is excluded
    print(i)

for i in range(1, 10, 2):  #range(1, 10, 2)  - 1 t0 9, 10 is excluded, step is 2.
    print(i)

for i in range(10, 0, -1):  #range(10, 0, -1)  - 10 to 1, 0 is excluded, step is -1.
    print(i)



# Note: range() function returns a range object, which is an immutable sequence type.
# As for loop traverses through the list or sequence, here, the range function generates akind of list to traverse through.
print(type(range(5)))  # <class 'range'>



