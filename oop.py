# Static Methods:
# Methods that don't use the self parameter(work at class level)
# Work at class level doesn't mean that
# static methods can access or modify class state and generally for utility.
  
# Example:  
# In above "student" class we have an average method where self parameter is unused
# So it can be written as: 

class student:
    def __init__(self, name, marks):
        self.name = name
        self.marks = marks
        
    @staticmethod
    def average():                                 # self -- parameter is removed. -- and works fine.
        average = (marks[0]+marks[1]+marks[2])/3
        return average
    
