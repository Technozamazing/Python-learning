class Complex:

    def __init__(self, real, img):
        self.real = real
        self.img = img
    
    def showNumber(self):
        print(f'{self.real} + {self.img}j')

    def __add__(self, num2):
        newReal = self.real + num2.real
        newimg = self.img + num2.img
        return Complex(newReal, newimg)
        
